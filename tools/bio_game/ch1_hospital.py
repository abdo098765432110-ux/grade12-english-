def W(text, why):
    return {"text": text, "why": why}


def S(who, lines, mood=None, context=None, bg=None):
    s = {"who": who, "lines": lines}
    if mood: s["mood"] = mood
    if context: s["context"] = context
    if bg: s["bg"] = bg
    return s


