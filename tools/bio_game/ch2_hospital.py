CASES = []


def S(who, lines, mood=None, bg=None, context=None, signs=None):
    s = {"who": who, "lines": lines}
    if mood: s["mood"] = mood
    if bg: s["bg"] = bg
    if context: s["context"] = context
    if signs: s["signs"] = signs
    return s


def C(cid, idea, level, ctype, stories, question, answer, wrong, explain, exam=None, after=None):
    c = {"id": cid, "idea": idea, "level": level, "type": ctype, "stories": stories, "question": question,
         "answer": answer, "wrong": [{"text": t, "why": w} for t, w in wrong], "explain": explain}
    if exam: c["exam"] = exam
    if after: c["after"] = after
    CASES.append(c)


def X(view, label, opts=None, kind=None, finding=None):
    e = {"label": label, "view": view}
    if opts: e["opts"] = opts
    if kind: e["kind"] = kind
    if finding: e["finding"] = finding
    return e


def R(title, rows, note=None, label="شوف التقرير"):
    opts = {"title": title, "rows": rows}
    if note: opts["note"] = note
    return X("report", label, opts)


