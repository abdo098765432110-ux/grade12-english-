# ------------------------------------------------------------------ 14. skull
def skull(s, ox, oy, face=1.0):
    def F(x, y):  # enlarge the face and jaw around the point (165, 115)
        if face == 1.0:
            return x, y
        cx, cy = 165, 112
        if x < 175 and y > 115:
            return cx + (x - cx) * face, cy + (y - cy) * face
        return x, y
    def T(pts):
        return [(ox + a, oy + b) for a, b in (F(x, y) for x, y in pts)]
    cran = T([(250, 205), (275, 150), (268, 70), (195, 30), (125, 8), (50, 35), (28, 105)])
    face_pts = T([(28, 105), (40, 128), (28, 152), (22, 170), (36, 200), (48, 215), (120, 215), (168, 196), (212, 188), (250, 205)])
    d = smooth(cran + face_pts[1:], 0.16) + " Z"
    s.path(d, BONE, BONELINE, 3)
    jaw = T([(42, 222), (40, 255), (55, 278), (130, 282), (178, 250), (182, 205), (166, 196), (150, 222), (120, 222), (42, 222)])
    s.path(smooth(jaw, 0.12) + " Z", BONE, BONELINE, 3)
    # teeth
    for i in range(7):
        x, y = F(48 + i * 12, 208)
        s.rect(ox + x, oy + y, 9 * face, 13 * face, fill=WHITE, stroke=BONELINE, sw=1.5, rx=2)
        x, y = F(48 + i * 12, 223)
        s.rect(ox + x, oy + y, 9 * face, 12 * face, fill=WHITE, stroke=BONELINE, sw=1.5, rx=2)
    ex, ey = F(78, 120)
    s.ellipse(ox + ex, oy + ey, 26 * face, 23 * face, fill="#6b5b45", stroke=BONELINE, sw=2)
    nx, ny = F(40, 166)
    s.path("M%s %s q-12 18 0 32 q12 -14 0 -32 Z" % (f(ox + nx), f(oy + ny)), "#6b5b45", BONELINE, 2)
    zx, zy = F(105, 160)
    s.path("M%s %s q50 -12 90 4" % (f(ox + zx), f(oy + zy)), "none", BONELINE, 3)
    s.circle(ox + 222, oy + 165, 9, fill="#6b5b45", stroke=BONELINE, sw=2)
    # sutures on the cranium
    s.path("M%s %s q8 -20 0 -40 q-8 -20 4 -44" % (f(ox + 160), f(oy + 110)), "none", BONELINE, 2, 'stroke-dasharray="4 4"')


