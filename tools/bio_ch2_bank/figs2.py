# ------------------------------------------------------------------ 13. hand bones
def bone(s, x1, y1, x2, y2, w, fill=BONE):
    ang = math.atan2(y2 - y1, x2 - x1)
    L = math.hypot(x2 - x1, y2 - y1)
    cx, cy = (x1 + x2) / 2, (y1 + y2) / 2
    deg = math.degrees(ang)
    hw = w / 2
    d = ("M %s %s C %s %s %s %s %s %s L %s %s C %s %s %s %s %s %s Z" % (
        f(-L / 2), f(-hw * 1.25), f(-L / 2 - hw * 0.9), f(-hw * 1.2), f(-L / 2 - hw * 0.9), f(hw * 1.2), f(-L / 2), f(hw * 1.25),
        f(L / 2), f(hw * 1.15), f(L / 2 + hw * 0.9), f(hw * 1.1), f(L / 2 + hw * 0.9), f(-hw * 1.1), f(L / 2), f(-hw * 1.15)))
    d = d.replace("L %s %s" % (f(L / 2), f(hw * 1.15)), "C %s %s %s %s %s %s" % (f(-L / 4), f(hw * 0.75), f(L / 4), f(hw * 0.75), f(L / 2), f(hw * 1.15)))
    d = d.replace("Z", "C %s %s %s %s %s %s Z" % (f(L / 4), f(-hw * 0.75), f(-L / 4), f(-hw * 0.75), f(-L / 2), f(-hw * 1.25)))
    s.path(d, fill, BONELINE, 2.5, 'transform="translate(%s %s) rotate(%s)"' % (f(cx), f(cy), f(deg)))


def hand(s, ox, oy, k=1.0, wide=1.0, long=1.0):
    pts = {}
    # carpals: two rows of four
    for row, y in ((0, 0), (1, -34)):
        for i in range(4):
            x = -48 + i * 32
            s.path(blob(ox + x * k, oy + y * k, 15 * k * wide, 0.12, 7, seed=row * 4 + i + 1), BONE, BONELINE, 2.5)
            pts["c%d%d" % (row, i)] = (ox + x * k, oy + y * k)
    # forearm ends
    bone(s, ox - 30 * k, oy + 30 * k, ox - 30 * k, oy + 110 * k, 34 * k * wide)
    bone(s, ox + 30 * k, oy + 30 * k, ox + 30 * k, oy + 110 * k, 26 * k * wide)
    fingers = [  # base x, angle (deg from up), metacarpal, phalanges
        (-60, -38, 62, (48, 34)),
        (-34, -8, 92, (58, 36, 26)),
        (-4, 0, 96, (62, 40, 28)),
        (26, 7, 90, (58, 38, 26)),
        (52, 15, 80, (46, 30, 24)),
    ]
    for j, (bx, ang, meta, phal) in enumerate(fingers):
        a = math.radians(ang)
        dx, dy = math.sin(a), -math.cos(a)
        x, y = ox + bx * k, oy - (40 if j == 0 else 58) * k
        segs = [meta] + list(phal)
        for i, L in enumerate(segs):
            L = L * k * long
            w = (16 if i == 0 else 14 - i * 2) * k * wide
            if j == 0:
                w *= 1.15
            x2, y2 = x + dx * L, y + dy * L
            bone(s, x, y, x2, y2, w)
            pts["f%d_%d" % (j, i)] = ((x + x2) / 2, (y + y2) / 2)
            x, y = x2 + dx * 6 * k, y2 + dy * 6 * k
    return pts


