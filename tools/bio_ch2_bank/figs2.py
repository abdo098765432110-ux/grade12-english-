# ------------------------------------------------------------------ 16. blood pressure and heart rate after three extracts
def fig16():
    s = SVG(780, 640)
    t = [x / 2 for x in range(0, 121)]
    def rise(x, at, peak, up=2.5, down=7.0):
        if x <= at:
            return 0.0
        u = x - at
        return peak * (1 - math.exp(-u / up)) * math.exp(-max(0.0, u - 3) / down)
    def bp(x):
        return 100 + rise(x, 20, 30) + rise(x, 50, 44, 1.8, 6)
    def hr(x):
        return 75 + rise(x, 50, 36, 1.8, 6)
    top = Axes(s, 130, 60, 590, 210, (0, 60), (80, 150), "", "ضغط الدم (مم زئبق)", [(v, "") for v in range(0, 61, 10)], [(v, str(v)) for v in (80, 100, 120, 140)], ylabel_size=20)
    top.curve([(x, bp(x)) for x in t], RED, 4.5, smooth_it=False)
    bot = Axes(s, 130, 350, 590, 190, (0, 60), (60, 120), "الزمن (دقيقة)", "ضربات القلب (نبضة/دقيقة)", [(v, str(v)) for v in range(0, 61, 10)], [(v, str(v)) for v in (60, 80, 100, 120)], ylabel_size=20)
    bot.curve([(x, hr(x)) for x in t], BLUE, 4.5, smooth_it=False)
    for v, n in ((10, 1), (20, 2), (50, 3)):
        for ax in (top, bot):
            X = ax.X(v)
            s.line(X, ax.y0, X, ax.y0 + ax.h, stroke=SOFT, sw=2, dash="6 6")
        s.num(top.X(v), 40, n, r=16)
    s.text(420, 622, "الأرقام: لحظات الحقن بالمستخلصات الثلاثة", size=19, fill=SOFT, weight=700)
    return s


